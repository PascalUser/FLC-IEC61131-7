"""Evidence contract for the canonical source-backed statistics snapshot.

A fingerprint proves that the snapshot references the current inputs, not that
JaCoCo was produced by a fresh build. Coverage must be described accordingly.
"""
import hashlib
from pathlib import Path

SCHEMA_VERSION = 2
MODULES = ("lexer", "parser", "ast", "generator", "repository")
INPUT_ROOTS = ("src/main/java", "src/test/java")
COVERAGE_PATH = "target/site/jacoco/jacoco.xml"


def input_fingerprint(root):
    """Hash the actual source and coverage inputs in deterministic path order."""
    root = Path(root)
    files = []
    for relative in INPUT_ROOTS:
        base = root / relative
        if not base.is_dir():
            raise ValueError("Missing metrics input directory: " + relative)
        files.extend(p for p in base.rglob("*")
                     if p.is_file() and p.suffix in {".java", ".y", ".flex"})
    for relative in (COVERAGE_PATH, "pom.xml"):
        path = root / relative
        if path.is_file():
            files.append(path)
    digest = hashlib.sha256()
    for path in sorted(files, key=lambda p: p.relative_to(root).as_posix()):
        relative = path.relative_to(root).as_posix().encode("utf-8")
        digest.update(len(relative).to_bytes(4, "big"))
        digest.update(relative)
        digest.update(hashlib.sha256(path.read_bytes()).digest())
    return digest.hexdigest()


def provenance(root):
    """Describe exactly what the current canonical values measure."""
    return {
        "schema_version": SCHEMA_VERSION,
        "input_sha256": input_fingerprint(root),
        "methodology": {
            "modules": {
                "sources": ["src/main/java/compiler/{module}/**/*.java"],
                "method": "Count handwritten and generated Java files except package-info; count nonblank/non-comment-only lines (proxy, not standardized LOC).",
            },
            "tests": {
                "sources": ["src/test/java/**/*.java"],
                "method": "Count Java files and filename suffixes Test.java and IT.java; this is not test coverage.",
            },
            "jacoco_line_coverage": {
                "sources": [COVERAGE_PATH],
                "method": "Read LINE counters from JaCoCo XML for compiler.* packages; report absent when XML does not exist.",
                "limitation": "A present XML report is not proof it was generated by a fresh test run. Run mvn verify before citing coverage.",
            },
        },
    }


def count_non_comment_lines(path):
    """Use the same explicitly documented LOC proxy as the overview generator."""
    count = 0
    in_block_comment = False
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        text = line.strip()
        if not text:
            continue
        if in_block_comment:
            if "*/" in text:
                in_block_comment = False
            continue
        if text.startswith("//"):
            continue
        if text.startswith("/*"):
            if "*/" not in text[2:]:
                in_block_comment = True
            continue
        if text.startswith("*") or text.startswith("*/"):
            continue
        count += 1
    return count


def validate_statistics(data, root):
    """Reject legacy, incomplete, or stale snapshots before thesis synthesis."""
    if not isinstance(data, dict) or data.get("schema_version") != SCHEMA_VERSION:
        raise ValueError("Canonical statistics schema_version=2 is required; regenerate general statistics")
    if data.get("input_sha256") != input_fingerprint(root):
        raise ValueError("Statistics are stale relative to source or JaCoCo inputs; regenerate them")
    methodology = data.get("methodology")
    if not isinstance(methodology, dict) or any(
        not isinstance(methodology.get(k), dict)
        or not methodology[k].get("sources")
        or not methodology[k].get("method")
        for k in ("modules", "tests", "jacoco_line_coverage")
    ):
        raise ValueError("Statistics lack verifiable methodology and source paths")
    modules = data.get("modules")
    if not isinstance(modules, dict) or set(modules) != set(MODULES):
        raise ValueError("Statistics have missing or unexpected production modules")
    for name in MODULES:
        values = modules[name]
        if not isinstance(values, dict):
            raise ValueError("Malformed metrics for " + name)
        count = values.get("java_files")
        loc = values.get("non_comment_lines")
        if type(count) is not int or count < 0 or type(loc) is not int or loc < 0:
            raise ValueError("Invalid source counts for " + name)
        sources = [p for p in (Path(root) / "src/main/java/compiler" / name).rglob("*.java")
                   if p.name != "package-info.java"]
        if count != len(sources) or loc != sum(count_non_comment_lines(p) for p in sources):
            raise ValueError("Source counts disagree with files for " + name)
    tests = data.get("tests")
    if not isinstance(tests, dict) or any(type(tests.get(k)) is not int or tests[k] < 0
            for k in ("java_files", "unit_test_classes", "integration_test_classes")):
        raise ValueError("Invalid test source counts")
    test_sources = [p for p in (Path(root) / "src/test/java").rglob("*.java")
                    if p.name != "package-info.java"]
    if (tests["java_files"] != len(test_sources)
            or tests["unit_test_classes"] != sum(p.name.endswith("Test.java") for p in test_sources)
            or tests["integration_test_classes"] != sum(p.name.endswith("IT.java") for p in test_sources)):
        raise ValueError("Test source counts disagree with files")
    cov = data.get("jacoco_line_coverage")
    if cov is not None:
        if not (Path(root) / COVERAGE_PATH).is_file():
            raise ValueError("Coverage asserted without a JaCoCo XML report")
        if not isinstance(cov, dict) or any(type(cov.get(k)) is not int or cov[k] < 0
                                            for k in ("covered_lines", "missed_lines")):
            raise ValueError("Invalid JaCoCo line counters")
        total = cov["covered_lines"] + cov["missed_lines"]
        expected = round(100 * cov["covered_lines"] / total, 1) if total else None
        if cov.get("overall_percent") != expected:
            raise ValueError("JaCoCo percentage disagrees with line counters")
    return data
