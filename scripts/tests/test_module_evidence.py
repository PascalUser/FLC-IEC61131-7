"""Offline contract tests for source-first module evidence inventories."""
from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path

from scripts.extract_module_evidence import (
    build_module_evidence, discover_modules, write_module_evidence,
)


class ModuleEvidenceTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.put("src/main/java/compiler/parser/Parser.java", '''
// A Bison parser, made by GNU Bison 3.8.2.
package compiler.parser;
import compiler.repository.SymbolTable;
// class Fake {}
public class Parser { class Nested { } String message = "class Pretend {}"; }
'''.lstrip())
        self.put("src/main/java/compiler/parser/facades/DimensionCalculator.java", '''
package compiler.parser.facades;
import java.util.List;
public final class DimensionCalculator {
  public static int calculate(List<String> limits) { return limits.size(); }
}
'''.lstrip())
        self.put("src/main/java/compiler/repository/SymbolTable.java", '''
package compiler.repository;
public final class SymbolTable {}
'''.lstrip())
        self.put("src/test/java/unit/parser/ParserTest.java", '''
package unit.parser;
import compiler.parser.Parser;
class ParserTest { private Parser parser; }
'''.lstrip())
        self.put("src/test/java/unit/repository/RepositoryTest.java", '''
package unit.repository;
import compiler.repository.SymbolTable;
class RepositoryTest { private SymbolTable table; }
'''.lstrip())
        self.put("src/main/java/compiler/parser/Parser.y", "%language \"Java\"\n%token FOO BAR\n")
        self.put("doc/modules/parser.md", "Bogus claim: 82 tokens and 141 non-terminals\n")
        self.put("doc/stats_general.json", '{"parser": {"fake_coverage": 99}}\n')

    def put(self, rel: str, value: str):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value, encoding="utf-8")

    def test_module_sources_packages_and_explicit_relations_have_locations(self):
        report = build_module_evidence(self.root, "parser")
        self.assertEqual(report["module"], "parser")
        self.assertEqual([p["name"] for p in report["packages"]],
                         ["compiler.parser", "compiler.parser.facades"])
        files = report["production_files"]
        self.assertEqual(len(files), 2)
        self.assertEqual(files[0]["generated_by"], "GNU Bison")
        self.assertEqual([d["name"] for d in files[0]["types"]], ["Parser"])
        self.assertEqual(files[0]["types"][0]["line"], 5)
        self.assertEqual(len(report["import_relations"]), 1)
        rel = report["import_relations"][0]
        self.assertEqual((rel["target_package"], rel["source_line"]),
                         ("compiler.repository", 3))
        self.assertEqual(len(report["related_tests"]), 1)
        self.assertEqual(report["related_tests"][0]["path"],
                         "src/test/java/unit/parser/ParserTest.java")
        self.assertTrue(any(e["kind"] == "explicit_import"
                            for e in report["related_tests"][0]["association_evidence"]))
        self.assertEqual(report["specifications"][0]["kind"], "bison_grammar")
        self.assertEqual(report["specifications"][0]["directive_locations"],
                         [{"directive": "language", "line": 1},
                          {"directive": "token", "line": 2}])

    def test_generated_labels_require_generator_header(self):
        source = self.root / "src/main/java/compiler/parser/Parser.java"
        source.write_text(source.read_text().replace("// A Bison parser, made by GNU Bison 3.8.2.\n", ""))
        report = build_module_evidence(self.root, "parser")
        self.assertIsNone(report["production_files"][0]["generated_by"])
        self.put("src/main/java/compiler/lexer/Lexer.java", """// DO NOT EDIT
// Generated by JFlex 1.8.2
package compiler.lexer;
public final class Lexer {}
""")
        lexer = build_module_evidence(self.root, "lexer")
        self.assertEqual(lexer["production_files"][0]["generated_by"], "JFlex")

    def test_does_not_trust_existing_document_or_statistics(self):
        original = build_module_evidence(self.root, "parser")
        self.assertEqual(next(m for m in original["metric_sources"]
                              if m["name"] == "canonical_statistics_snapshot")["status"],
                         "candidate_unverified")
        self.assertIsNone(next(m for m in original["metric_sources"]
                               if m["name"] == "grammar_token_and_production_counts")["value"])
        # Changing *only* old documentation and stale charts must not change facts.
        self.put("doc/modules/parser.md", "99% accuracy, another invented narrative\n")
        self.put("doc/stats_general.json", '{"parser": {"fake_coverage": 1}}\n')
        self.assertEqual(original, build_module_evidence(self.root, "parser"))

    def test_content_fingerprint_detects_source_changes_and_is_repeatable(self):
        a = build_module_evidence(self.root, "parser")
        self.assertEqual(a, build_module_evidence(self.root, "parser"))
        self.put("src/main/java/compiler/repository/SymbolTable.java", '''
package compiler.repository;
public final class SymbolTable { int size; }
'''.lstrip())
        b = build_module_evidence(self.root, "parser")
        self.assertNotEqual(a["snapshot"]["sha256"], b["snapshot"]["sha256"])
        self.assertEqual(a["production_files"], b["production_files"])

    def test_writes_only_evidence_json_and_rejects_invalid_modules(self):
        self.assertEqual(discover_modules(self.root), ["parser", "repository"])
        paths = write_module_evidence(self.root, ["parser"])
        self.assertEqual(len(paths), 1)
        self.assertEqual(paths[0].relative_to(self.root).as_posix(),
                         "output/evidence/modules/parser.json")
        data = json.loads(paths[0].read_text())
        self.assertEqual(data, build_module_evidence(self.root, "parser"))
        first_bytes = paths[0].read_bytes()
        write_module_evidence(self.root, ["parser"])
        self.assertEqual(first_bytes, paths[0].read_bytes())
        with self.assertRaisesRegex(ValueError, "Invalid module"):
            write_module_evidence(self.root, ["../repository"])
        with self.assertRaisesRegex(ValueError, "No production Java module"):
            write_module_evidence(self.root, ["missing"])
        self.assertFalse((self.root / "output/evidence/modules/repository.json").exists())

    def test_output_symlink_cannot_redirect_writes_into_tracked_docs(self):
        (self.root / "output").symlink_to(self.root / "doc", target_is_directory=True)
        with self.assertRaisesRegex(ValueError, "Unsafe symlink"):
            write_module_evidence(self.root, ["parser"])
        self.assertFalse((self.root / "doc/evidence").exists())

    def test_missing_required_test_tree_fails_closed(self):
        test_file = self.root / "src/test/java/unit/parser/ParserTest.java"
        test_file.unlink()
        (self.root / "src/test/java/unit/repository/RepositoryTest.java").unlink()
        with self.assertRaisesRegex(ValueError, "Missing test source root"):
            # scan_source still sees a directory until we remove it.
            import shutil
            shutil.rmtree(self.root / "src/test/java")
            build_module_evidence(self.root, "parser")


if __name__ == "__main__":
    unittest.main()
