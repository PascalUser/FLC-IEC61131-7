#!/usr/bin/env python3
"""Deterministic source-first evidence inventories for compiler modules (0042).

Only Java sources, Bison/JFlex specifications, and test Java are treated as
facts. Existing Markdown, charts, and statistics are not evidence of behavior.
Outputs are JSON files in output/evidence/modules; no tracked file is modified.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path

if __package__:
    from .extract_architecture import (
        IMPORT_PATTERN, TYPE_OR_BRACE, resolve_package, scan_source,
        without_comments_and_literals,
    )
else:
    from extract_architecture import (
        IMPORT_PATTERN, TYPE_OR_BRACE, resolve_package, scan_source,
        without_comments_and_literals,
    )

ROOT = Path(__file__).resolve().parents[1]
PRODUCTION = Path("src/main/java")
TESTS = Path("src/test/java")
COMPILER = PRODUCTION / "compiler"
OUTPUT = Path("output/evidence/modules")
MODULE_NAME = re.compile(r"[a-z][a-z0-9_]*\Z")
GENERATED_FILES = {
    "src/main/java/compiler/parser/Parser.java": "GNU Bison",
    "src/main/java/compiler/lexer/Lexer.java": "JFlex",
}
SPEC_KINDS = {".y": "bison_grammar", ".flex": "jflex_lexer"}


def sha256_file(path: Path) -> str:
    """Fingerprint the exact current bytes, not a cached Markdown claim."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source_file_index(root: Path, java_records: list[dict]) -> list[dict]:
    """Stable source snapshot of *all* scanned Java, grammar and lexer files."""
    paths = {r["path"] for r in java_records}
    # Include package-info.java and module-info.java in the fingerprint even
    # though the shared declaration scanner intentionally skips those files.
    for base in (root / PRODUCTION, root / TESTS):
        paths.update(p.relative_to(root).as_posix() for p in base.rglob("*.java"))
    for base in (root / COMPILER,):
        for ext in SPEC_KINDS:
            paths.update(p.relative_to(root).as_posix() for p in base.rglob("*" + ext))
    result = []
    for rel in sorted(paths):
        path = root / rel
        if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(root):
            raise ValueError("Unsafe source file: " + rel)
        result.append({"path": rel, "sha256": sha256_file(path)})
    return result


def snapshot_digest(index: list[dict]) -> str:
    """Content-addressed input snapshot, stable across repeated executions."""
    digest = hashlib.sha256()
    for entry in index:
        path = entry["path"].encode("utf-8")
        digest.update(len(path).to_bytes(4, "big"))
        digest.update(path)
        digest.update(bytes.fromhex(entry["sha256"]))
    return digest.hexdigest()


def declaration_lines(cleaned: str) -> dict[tuple[str, str], list[int]]:
    """Find lexical lines of top-level types; nested declarations stay excluded."""
    depth = 0
    found: dict[tuple[str, str], list[int]] = defaultdict(list)
    for match in TYPE_OR_BRACE.finditer(cleaned):
        if match.group(0) == "{":
            depth += 1
        elif match.group(0) == "}":
            depth -= 1
        elif depth == 0:
            kind = "annotation" if match.group(1) == "@interface" else match.group(1)
            found[(kind, match.group(2))].append(cleaned.count("\n", 0, match.start()) + 1)
    return found


def generated_origin(path: str, source: str) -> str | None:
    """Label known generated files only when their source header confirms it."""
    expected = GENERATED_FILES.get(path)
    header = source[:1024]
    if expected == "GNU Bison" and "made by GNU Bison" in header:
        return expected
    if expected == "JFlex" and "Generated by JFlex" in header:
        return expected
    return None


def indexed_java(record: dict, root: Path, packages: set[str]) -> dict:
    """Enrich the shared Java scanner with exact path/line evidence."""
    rel = record["path"]
    source = (root / rel).read_text(encoding="utf-8")
    cleaned = without_comments_and_literals(source)
    locations = declaration_lines(cleaned)
    declarations = []
    for decl in record["types"]:
        key = (decl["kind"], decl["name"])
        if not locations[key]:
            raise ValueError("Could not locate declaration: " + rel + ":" + decl["name"])
        declarations.append({**decl, "line": locations[key].pop(0),
                             "same_name_as_file": Path(rel).stem == decl["name"]})
    imports = []
    for match in IMPORT_PATTERN.finditer(cleaned):
        name = match.group(2) + (".*" if match.group(3) else "")
        imports.append({
            "name": name, "static": bool(match.group(1)),
            "line": cleaned.count("\n", 0, match.start()) + 1,
            "resolved_package": resolve_package(name, packages),
        })
    imports.sort(key=lambda item: (item["line"], item["name"], item["static"]))
    return {
        "path": rel, "sha256": sha256_file(root / rel), "package": record["package"],
        "generated_by": generated_origin(rel, source), "types": declarations,
        "imports": imports,
    }


def evidence_for_test(test: dict, module: str) -> list[dict]:
    """Only literal source ties; candidates do not prove executed test coverage."""
    target = "compiler." + module
    evidence = []
    if module in test["package"].split("."):
        evidence.append({"kind": "package_name", "path": test["path"],
                         "line": None, "value": test["package"]})
    for imp in test["imports"]:
        if imp["name"] == target or imp["name"].startswith(target + "."):
            evidence.append({"kind": "explicit_import", "path": test["path"],
                             "line": imp["line"], "value": imp["name"]})
    return evidence


def auxiliary_sources(root: Path, module: str) -> list[dict]:
    """List grammar/lexer sources; do not infer token, rule or branch counts."""
    base = root / COMPILER / module
    specs = []
    for path in sorted(base.rglob("*")):
        if path.suffix not in SPEC_KINDS or not path.is_file():
            continue
        rel = path.relative_to(root).as_posix()
        result = {"path": rel, "kind": SPEC_KINDS[path.suffix],
                  "sha256": sha256_file(path)}
        if path.suffix == ".y":
            # Declaration locations, not guessed token/production counts.
            matcher = re.compile(r"^\s*%(token|nterm|type|start|parse-param|language|define)\b")
            result["directive_locations"] = [
                {"directive": match.group(1), "line": n}
                for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1)
                if (match := matcher.match(line))
            ]
        specs.append(result)
    return specs


def validate_module(root: Path, name: str) -> None:
    """Reject arbitrary paths and nonexistent module scopes."""
    if not MODULE_NAME.fullmatch(name):
        raise ValueError("Invalid module identifier: " + repr(name))
    path = root / COMPILER / name
    if not path.is_dir() or path.is_symlink() or not any(path.rglob("*.java")):
        raise ValueError("No production Java module: " + name)


def build_module_evidence(root: Path, module: str, *, java_records: list[dict] | None = None,
                          file_index: list[dict] | None = None) -> dict:
    """Produce source-backed module facts without reading module documentation."""
    root = Path(root).resolve()
    validate_module(root, module)
    if java_records is None:
        java_records = (scan_source(root, PRODUCTION, "production") +
                        scan_source(root, TESTS, "test"))
    if file_index is None:
        file_index = source_file_index(root, java_records)
    all_packages = {r["package"] for r in java_records}
    target = "compiler." + module
    production = [indexed_java(r, root, all_packages)
                  for r in java_records if r["scope"] == "production"
                  and (r["package"] == target or r["package"].startswith(target + "."))]
    production.sort(key=lambda item: item["path"])
    if not production:
        raise ValueError("Missing production package declarations for " + module)
    tests = []
    for record in java_records:
        if record["scope"] != "test":
            continue
        indexed = indexed_java(record, root, all_packages)
        associations = evidence_for_test(indexed, module)
        if associations:
            tests.append({"path": indexed["path"], "sha256": indexed["sha256"],
                          "package": indexed["package"], "types": indexed["types"],
                          "association_evidence": associations})
    tests.sort(key=lambda item: item["path"])
    packages = [{"name": pkg, "source_files": [r["path"] for r in production if r["package"] == pkg]}
                for pkg in sorted({r["package"] for r in production})]
    relations = []
    for file in production:
        for imp in file["imports"]:
            if imp["resolved_package"] and imp["resolved_package"] != file["package"]:
                relations.append({"kind": "explicit_import", "source_path": file["path"],
                                  "source_line": imp["line"], "import_name": imp["name"],
                                  "target_package": imp["resolved_package"]})
    relations.sort(key=lambda e: (e["source_path"], e["source_line"], e["import_name"]))
    specs = auxiliary_sources(root, module)
    # Existing statistics are listed as *candidates*, never as verified values.
    stats = root / "doc/stats_general.json"
    metric_sources = [
        {"name": "java_file_inventory", "status": "computed_from_sources",
         "source_files": [r["path"] for r in production],
         "value": len(production), "unit": "Java source files",
         "caveat": "Includes generated files; count is not a quality metric."},
        {"name": "canonical_statistics_snapshot", "status": "candidate_unverified" if stats.is_file() else "absent",
         "path": "doc/stats_general.json", "value": None,
         "caveat": "No statistics are imported; verify snapshot provenance separately."},
    ]
    if any(s["kind"] == "bison_grammar" for s in specs):
        metric_sources.append({"name": "grammar_token_and_production_counts", "status": "not_computed",
                               "source_files": [s["path"] for s in specs if s["kind"] == "bison_grammar"],
                               "value": None, "caveat": "Requires a dedicated validated grammar extractor."})
    return {
        "schema_version": 1, "module": module,
        "source_root": (COMPILER / module).as_posix(),
        "snapshot": {"sha256": snapshot_digest(file_index),
                     "scope": "All production/test Java and Bison/JFlex source files in src/main/java/compiler and src/test/java",
                     "module_files": [f for f in file_index if f["path"].startswith((COMPILER / module).as_posix() + "/")],
                     "associated_test_files": [{"path": x["path"], "sha256": x["sha256"]} for x in tests]},
        "packages": packages, "production_files": production, "related_tests": tests,
        "specifications": specs, "import_relations": relations,
        "metric_sources": metric_sources,
        "limitations": [
            "Java parsing is lexical: only top-level declarations and explicit imports are extracted.",
            "An import relation is not evidence of runtime call flow or a resolved type binding.",
            "Tests are associated by package names or explicit imports; no test execution or coverage is claimed.",
            "Generated Java files are labelled and may not reflect handwritten design choices.",
            "No prose, chart, archived statistics or existing module Markdown is treated as evidence.",
            "Grammar token and production counts, complexity and JaCoCo coverage are not inferred.",
        ],
    }


def discover_modules(root: Path) -> list[str]:
    """Discover current module directories from the production source tree."""
    path = root / COMPILER
    if not path.is_dir():
        raise ValueError("Missing production compiler root: " + COMPILER.as_posix())
    return sorted(p.name for p in path.iterdir() if p.is_dir() and not p.is_symlink()
                  and MODULE_NAME.fullmatch(p.name) and any(p.rglob("*.java")))


def write_module_evidence(root: Path, modules: list[str]) -> list[Path]:
    """Write only output/evidence/modules/<module>.json after all inventories pass."""
    root = root.resolve()
    if not modules:
        raise ValueError("No modules selected")
    for module in modules:
        validate_module(root, module)
    records = scan_source(root, PRODUCTION, "production") + scan_source(root, TESTS, "test")
    index = source_file_index(root, records)
    reports = {name: build_module_evidence(root, name, java_records=records, file_index=index)
               for name in sorted(set(modules))}
    out = root / OUTPUT
    for part in (Path("output"), Path("output/evidence"), OUTPUT):
        if (root / part).is_symlink():
            raise ValueError("Unsafe symlink in evidence output path: " + part.as_posix())
    if not out.resolve().is_relative_to(root):
        raise ValueError("Unsafe evidence output directory")
    out.mkdir(parents=True, exist_ok=True)
    created = []
    for name, report in reports.items():
        dest = out / (name + ".json")
        if dest.is_symlink():
            raise ValueError("Refusing to overwrite symlink: " + str(dest))
        data = json.dumps(report, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
        dest.write_text(data, encoding="utf-8")
        created.append(dest)
    return created


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--modules", help="Comma-separated modules; default is all compiler subpackages")
    args = parser.parse_args()
    modules = [x.strip() for x in args.modules.split(",")] if args.modules is not None else discover_modules(ROOT)
    paths = write_module_evidence(ROOT, modules)
    for path in paths:
        print("Evidence inventory: " + path.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
