#!/usr/bin/env python3
"""Read-only audit of every registered Mermaid generator.

By default this checks that each generator runs and produces nonempty Mermaid.
Use --check-generated to additionally compare its output with doc/diagrams/*.mmd.
No diagrams are written or regenerated by this command.
"""
import argparse
import json
import sys
from pathlib import Path

import generate_diagrams


VALID_PREFIXES = (
    "flowchart ", "graph ", "sequenceDiagram", "classDiagram",
    "stateDiagram", "erDiagram", "journey", "gantt", "pie", "timeline",
    "mindmap", "quadrantChart", "requirementDiagram", "gitgraph", "C4Context",
)


def audit(generators, directory: Path, check_generated=False):
    """Return a deterministic report; never write or render a diagram."""
    results = []
    for name, generate in sorted(generators.items()):
        result = {"diagram": name, "status": "ok"}
        try:
            content = generate()
            if not isinstance(content, str) or not content.strip():
                raise ValueError("Generator returned empty or non-text Mermaid")
            first = content.lstrip().splitlines()[0].strip()
            if not first.startswith(VALID_PREFIXES):
                raise ValueError(f"Unrecognized Mermaid diagram type: {first[:80]}")
            if check_generated:
                target = directory / f"{name}.mmd"
                if not target.is_file():
                    result.update(status="missing", detail=str(target))
                elif target.read_text(encoding="utf-8").rstrip("\n") != content.rstrip("\n"):
                    result.update(status="stale", detail=str(target))
        except Exception as exc:
            result.update(status="failed", detail=f"{type(exc).__name__}: {exc}")
        results.append(result)
    summary = {status: sum(item["status"] == status for item in results)
               for status in ("ok", "failed", "missing", "stale")}
    return {"total": len(results), "summary": summary, "results": results}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-generated", action="store_true",
                        help="Also verify checked-in .mmd files match generated output")
    parser.add_argument("--json", action="store_true", help="Print machine-readable JSON")
    args = parser.parse_args(argv)

    report = audit(generate_diagrams.DIAGRAMS, generate_diagrams.DIAGRAMS_DIR,
                   check_generated=args.check_generated)
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        for item in report["results"]:
            detail = f" — {item['detail']}" if "detail" in item else ""
            print(f"{item['status'].upper():7} {item['diagram']}{detail}")
        print(f"Audited {report['total']} diagrams: " +
              ", ".join(f"{count} {status}" for status, count in report["summary"].items()))
    return 1 if any(report["summary"][status] for status in ("failed", "missing", "stale")) else 0


if __name__ == "__main__":
    sys.exit(main())
